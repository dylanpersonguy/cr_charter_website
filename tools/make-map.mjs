// Builds src/data/map-geo.mjs from Natural Earth 10m admin-0 (public domain).
// Usage: node tools/make-map.mjs <path-to-ne_10m_admin_0_countries.geojson>
import fs from 'node:fs';
const src = process.argv[2];
const gj = JSON.parse(fs.readFileSync(src, 'utf8'));
const BOX = { w: -86.05, e: -82.35, n: 11.32, s: 7.95 };
const LAT0 = 9.6, K = 260; // px per degree latitude
const kx = K * Math.cos(LAT0 * Math.PI / 180);
const W = Math.round((BOX.e - BOX.w) * kx), H = Math.round((BOX.n - BOX.s) * K);
const proj = ([lon, lat]) => [(lon - BOX.w) * kx, (BOX.n - lat) * K];
function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = 0, mi = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b]; const dx = x2 - x1, dy = y2 - y1; const L = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L; if (d > md) { md = d; mi = i; } }
    if (md > tol) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function pathFor(iso, tol, minArea) {
  const f = gj.features.find(f => f.properties.ADM0_A3 === iso || f.properties.ISO_A3 === iso);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  let d = '';
  for (const poly of polys) {
    const ring = poly[0].map(proj);
    const xs = ring.map(p => p[0]), ys = ring.map(p => p[1]);
    if (Math.max(...xs) < -50 || Math.min(...xs) > W + 50 || Math.max(...ys) < -50 || Math.min(...ys) > H + 50) continue;
    const area = (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys));
    if (area < minArea) continue;
    const mid = Math.floor(ring.length / 2); const s = dp(ring.slice(0, mid + 1), tol).concat(dp(ring.slice(mid), tol).slice(1));
    d += 'M' + s.map(p => p[0].toFixed(1) + ' ' + p[1].toFixed(1)).join('L') + 'Z';
  }
  return d;
}
const out = {
  width: W, height: H, box: BOX, lat0: LAT0, k: K,
  cr: pathFor('CRI', 0.6, 6),
  nic: pathFor('NIC', 1.2, 40),
  pan: pathFor('PAN', 1.2, 40),
};
fs.writeFileSync('src/data/map-geo.mjs',
  '// Generated by tools/make-map.mjs from Natural Earth 10m (public domain). Do not edit by hand.\n' +
  'export const mapGeo = ' + JSON.stringify(out) + ';\n' +
  `export function project(lat, lon) { const kx = ${K} * Math.cos(${LAT0} * Math.PI / 180); return [(lon - (${BOX.w})) * kx, (${BOX.n} - lat) * ${K}]; }\n`);
console.log('map', W, 'x', H, 'cr path chars', out.cr.length, 'nic', out.nic.length, 'pan', out.pan.length);

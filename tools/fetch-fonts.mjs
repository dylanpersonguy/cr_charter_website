// Self-host the site fonts (SIL Open Font License): node tools/fetch-fonts.mjs
// Downloads latin + latin-ext WOFF2 subsets of Fraunces & Inter and writes src/assets/css/fonts.css.
import fs from 'node:fs';
import path from 'node:path';

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300..700;1,9..144,300..600&family=Inter:wght@400;500;600;700&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const OUT = 'src/assets/fonts';
fs.mkdirSync(OUT, { recursive: true });

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face \{[^}]+\})/g)].filter(m => m[1] === 'latin' || m[1] === 'latin-ext');
const seen = new Map();
let out = '/* Generated by tools/fetch-fonts.mjs — Fraunces & Inter, SIL Open Font License 1.1 */\n';
for (const [, subset, block] of blocks) {
  const family = block.match(/font-family: '([^']+)'/)[1];
  const style = block.match(/font-style: (\w+)/)[1];
  const url = block.match(/url\(([^)]+)\)/)[1];
  let file = seen.get(url);
  if (!file) {
    file = `${family.toLowerCase()}-${style}-${subset}.woff2`;
    fs.writeFileSync(path.join(OUT, file), Buffer.from(await (await fetch(url)).arrayBuffer()));
    seen.set(url, file);
  }
  out += block.replace(/url\([^)]+\)/, `url(/assets/fonts/${file})`).replace(/\n\s*/g, ' ') + '\n';
}
fs.writeFileSync('src/assets/css/fonts.css', out);
console.log(`Saved ${seen.size} font files and ${blocks.length} @font-face rules.`);
